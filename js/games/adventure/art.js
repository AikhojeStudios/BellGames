  /** Draw a sprite at (x, y). Options: flip (mirror), scale, sx/sy/sw/sh (part of it). */
  function draw(ctx, name, x, y, { flip = false, scale = 1 } = {}) {
    const img = get(name);
    const w = img.width * scale;
    const hgt = img.height * scale;
    if (flip) {
      ctx.save();
      ctx.translate(Math.round(x) + w, Math.round(y));
      ctx.scale(-1, 1);
      ctx.drawImage(img, 0, 0, w, hgt);
      ctx.restore();
    } else {
      ctx.drawImage(img, Math.round(x), Math.round(y), w, hgt);
    }
  }

